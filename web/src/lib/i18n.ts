export const translations = { en, ur }
export type MessageKey = keyof typeof en

export function translate(language: Language, key: MessageKey, replacements: Record<string, string | number> = {}): string {
  return translations[language][key].replace(/\{(\w+)\}/g, (match, name: string) => String(replacements[name] ?? match))
}

export function number(value: number, language: Language): string {
  return new Intl.NumberFormat(language === 'ur' ? 'ur-PK-u-nu-arabext' : 'en').format(value)
}

export function date(value: string, language: Language): string {
  return new Intl.DateTimeFormat(language === 'ur' ? 'ur-PK' : 'en-GB', {
    day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC',
  }).format(new Date(`${value}T00:00:00Z`))
}
